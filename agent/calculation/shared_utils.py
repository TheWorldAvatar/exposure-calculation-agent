def instantiate_result_ontop(subject_to_value_dict: dict = None, calculation_input: CalculationInput = None):
    with postgis_client.connect() as conn:
        with conn.cursor() as cur:
            create_table = """
            CREATE TABLE IF NOT EXISTS exposure_result_set (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                exposure TEXT,
                calculation TEXT,
                mean double precision,
                sddev double precision
            );

            CREATE INDEX IF NOT EXISTS exposure_result_set_idx ON exposure_result_set(exposure, calculation);

            CREATE TABLE IF NOT EXISTS exposure_result (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                subject TEXT,
                exposure TEXT,
                calculation TEXT,
                value double precision,
                unit TEXT,
                z_score double precision,
                percentile double precision,
                set_id INT REFERENCES exposure_result_set(id) ON DELETE CASCADE,
                CONSTRAINT exposure_result_constraint UNIQUE (subject, exposure, calculation)
            );

            ALTER TABLE exposure_result
            ADD COLUMN IF NOT EXISTS z_score double precision,
            ADD COLUMN IF NOT EXISTS percentile double precision,
            ADD COLUMN IF NOT EXISTS set_id INT REFERENCES exposure_result_set(id) ON DELETE CASCADE;

            CREATE INDEX IF NOT EXISTS exposure_result_set_id_idx ON exposure_result(set_id);
            """
            cur.execute(create_table)

            data = []

            if calculation_input.calculation_metadata.rdf_type not in constants.TRAJECTORY_TYPES:
                values = [v.value for v in subject_to_value_dict.values()
                          if v.value is not None]
                mean = statistics.mean(values)
                sddev = statistics.stdev(values)

                set_id = _instantiate_result_set(
                    calculation_input, subject_to_value_dict, mean, sddev, conn)

                insert_query = """
                    INSERT INTO exposure_result (subject, exposure, calculation, value, unit, z_score, percentile, set_id)
                    VALUES %s
                    ON CONFLICT (subject, exposure, calculation)
                    DO UPDATE SET value = EXCLUDED.value,
                                  unit = EXCLUDED.unit,
                                  z_score = EXCLUDED.z_score,
                                  percentile = EXCLUDED.percentile,
                                  set_id = EXCLUDED.set_id
                """

                subject_to_z_score = _get_z_score(
                    subject_to_result_dict=subject_to_value_dict, mean=mean, sddev=sddev)
                subject_to_percentile = _get_percentile(subject_to_value_dict)

                for subject, value in subject_to_value_dict.items():
                    data.append((subject, calculation_input.exposure,
                                calculation_input.calculation_metadata.iri, value.value, value.unit, subject_to_z_score[subject], subject_to_percentile[subject], set_id))
            else:
                # trajectory case, only one subject
                data = [(calculation_input.subject, calculation_input.exposure,
                         calculation_input.calculation_metadata.iri, rdf_type_to_unit[calculation_input.calculation_metadata.rdf_type])]

                insert_query = """
                    INSERT INTO exposure_result (subject, exposure, calculation, unit)
                    VALUES %s
                    ON CONFLICT DO NOTHING
                """

            execute_values(cur, insert_query, data)

    # upload mapping only if it has not been uploaded
    logger.info('Uploading ontop mapping if it does not exist')
    _upload_ontop_mapping()


def _upload_ontop_mapping():
    from agent.utils.kg_client import kg_client

    # Don't make too general a query here. Look for a statement
    # that can be there only if the mapping has been uploaded.
    query = f"SELECT * WHERE {{?r a <{EXPOSURE_RESULT}>}} LIMIT 1"

    # currently fixed to the default ontop container
    query_result = json.loads(
        kg_client.ontop_client.executeQuery(query).toString())

    if not query_result:
        logger.info("Updating Ontop mapping...")
        ontop_mapping_path = Path('agent/calculation/resources/ontop.obda')

        path = stack_clients_view.java.nio.file.Paths.get(
            stack_clients_view.java.net.URI(ontop_mapping_path.resolve().as_uri()))
        ONTOP_CLIENT.updateOBDA(path)
        # Give Ontop some time to sort itself out.
        # It will not be ready immediately to take queries!
        time.sleep(30)
        # The following is essential. Otherwise the outgoing federation
        # will return nothing, or random garbage...
        of_rep_id = stack_clients_view.Rdf4jService.OUT_STACK_REPO_ID
        logger.info(f"Refreshing outgoing federation ('{of_rep_id}') cache...")
        stack_clients_view.Rdf4jClient.getInstance().refreshRepositoryCache(of_rep_id)
        time.sleep(5)


def get_iri_to_point_dict(subject):
    # returns points in EPSG:3857, to be used for ST_DWithin in queries
    from agent.utils.kg_client import kg_client
    if not isinstance(subject, list):
        subject = [subject]

    iri_to_point_dict = {}
    transformer = Transformer.from_crs(
        "EPSG:4326", "EPSG:3857", always_xy=True)

    query_template = """
    SELECT ?subject ?wkt
    WHERE {{
        VALUES ?subject {{{values}}}.
        ?subject <http://www.opengis.net/ont/geosparql#asWKT> ?wkt.
    }}
    """

    logger.info(
        'Querying geometries of subjects, number of subjects: ' + str(len(subject)))

    query_list = []
    # submit queries in batches to avoid crashing ontop
    for chunk in _chunk_list(subject):
        values = " ".join(f"<{s}>" for s in chunk)
        query = query_template.format(values=values)
        query_list.append(query)

    for query in query_list:
        query_result = json.loads(
            kg_client.remote_store_client.executeQuery(query).toString())

        for row in query_result:
            sub = row['subject']
            wkt_literal = row['wkt']

            # strip RDF literal IRI, i.e. ^^<http://www.opengis.net/ont/geosparql#wktLiteral>
            match = re.match(r'^"(.+)"\^\^<.+>$', wkt_literal)
            if match:
                geom = wkt.loads(match.group(1))
            else:
                geom = wkt.loads(wkt_literal)

            projected_geom = transform(transformer.transform, geom)
            iri_to_point_dict[sub] = projected_geom

    return iri_to_point_dict


def get_iri_to_buffer_dict(subject, distance: float):
    # returns buffers in 4326
    from agent.utils.kg_client import kg_client

    iri_to_buffer_dict = {}
    transformer = Transformer.from_crs(
        "EPSG:4326", "EPSG:3857", always_xy=True)

    transformer_back = Transformer.from_crs(
        "EPSG:3857", "EPSG:4326", always_xy=True)

    query_template = """
    SELECT ?subject ?wkt
    WHERE {{
        VALUES ?subject {{{values}}}.
        ?subject <http://www.opengis.net/ont/geosparql#asWKT> ?wkt.
    }}
    """

    logger.info(
        'Querying geometries of subjects, number of subjects: ' + str(len(subject)))

    query_list = []
    # submit queries in batches to avoid crashing ontop
    for chunk in _chunk_list(subject):
        values = " ".join(f"<{s}>" for s in chunk)
        query = query_template.format(values=values)
        query_list.append(query)

    for query in query_list:
        query_result = json.loads(
            kg_client.remote_store_client.executeQuery(query).toString())

        for row in query_result:
            sub = row['subject']
            wkt_literal = row['wkt']

            # strip RDF literal IRI, i.e. ^^<http://www.opengis.net/ont/geosparql#wktLiteral>
            match = re.match(r'^"(.+)"\^\^<.+>$', wkt_literal)
            if match:
                geom = wkt.loads(match.group(1))
            else:
                geom = wkt.loads(wkt_literal)

            projected_geom = transform(transformer.transform, geom)
            buffered_geom = projected_geom.buffer(distance)
            iri_to_buffer_dict[sub] = transform(
                transformer_back.transform, buffered_geom)

    return iri_to_buffer_dict


def _get_z_score(subject_to_result_dict: dict, mean, sddev):
    subject_to_z_score = {}

    for subject in subject_to_result_dict:
        if subject_to_result_dict[subject].value is not None:
            subject_to_z_score[subject] = (
                subject_to_result_dict[subject].value - mean) / sddev
        else:
            subject_to_z_score[subject] = None

    return subject_to_z_score


def _get_percentile(subject_to_result_dict: dict):
    # extract numerical value out of ExposureValue
    subject_to_value_dict = {}
    subjects_with_none = []
    for subject in subject_to_result_dict:
        if subject_to_result_dict[subject].value is None:
            subjects_with_none.append(subject)
        else:
            subject_to_value_dict[subject] = subject_to_result_dict[subject].value

    dataframe = pd.Series(subject_to_value_dict)

    percentiles = dataframe.rank(method="max", pct=True) * 100

    percentile_dict = percentiles.to_dict()

    for subject in subjects_with_none:
        percentile_dict[subject] = None

    return percentile_dict


def _instantiate_result_set(calculation_input: CalculationInput, subject_to_value_dict: dict, mean: float, sddev: float, conn):
    # check if result set with this combination of subjects exist
    query = """
        SELECT id
        FROM exposure_result_set
        WHERE exposure = %(EXPOSURE_PLACEHOLDER)s
        AND calculation = %(CALCULATION_PLACEHOLDER)s
    """

    replacements = {
        'EXPOSURE_PLACEHOLDER': calculation_input.exposure,
        'CALCULATION_PLACEHOLDER': calculation_input.calculation_metadata.iri
    }

    set_ids = []
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        cur.execute(query, replacements)
        if cur.description:
            query_result = cur.fetchall()
            for row in query_result:
                set_ids.append(row['id'])

    # existing set with this combo exist, but need to check if the subjects are identical as well
    if len(set_ids) > 0:
        query = """
        SELECT subject, set_id
        FROM exposure_result
        WHERE set_id = ANY(%(SET_ID_PLACEHOLDER)s)
        """

        replacements = {'SET_ID_PLACEHOLDER': set_ids}
        set_id_to_subjects = defaultdict(set)
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute(query, replacements)
            if cur.description:
                query_result = cur.fetchall()
                for row in query_result:
                    subject = row['subject']
                    set_id = row['set_id']
                    set_id_to_subjects[set_id].add(subject)

        # find set_id that contains all subjects
        current_subject_set = set(subject_to_value_dict.keys())

        set_id_to_use = None
        for set_id in set_id_to_subjects:
            if set_id_to_subjects[set_id] == current_subject_set:
                set_id_to_use = set_id

        if set_id_to_use is None:
            set_id_to_use = _get_new_set_id(
                calculation_input, mean, sddev, conn)
        else:
            _overwrite_result_id(set_id_to_use, mean, sddev, conn)

    else:
        set_id_to_use = _get_new_set_id(calculation_input, mean, sddev, conn)

    return set_id_to_use


def _get_new_set_id(calculation_input: CalculationInput, mean, sddev, conn):
    # initialise a new result set
    insert_query = """
        INSERT INTO exposure_result_set (exposure, calculation, mean, sddev)
        VALUES %s
        RETURNING id;
    """
    data = [(calculation_input.exposure,
            calculation_input.calculation_metadata.iri, mean, sddev)]
    new_set_id = None
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        execute_values(cur, insert_query, data)
        if cur.description:
            query_result = cur.fetchall()
            new_set_id = query_result[0]['id']

    if new_set_id is not None:
        return new_set_id
    else:
        raise Exception('set id was not initialised')


def _overwrite_result_id(set_id, mean, sddev, conn):
    insert_query = """
    INSERT INTO exposure_result_set (id, mean, sddev)
    VALUES %s
    ON CONFLICT (id)
    DO UPDATE SET mean = EXCLUDED.mean,
                sddev = EXCLUDED.sddev
    """
    data = [(set_id, mean, sddev)]
    with conn.cursor() as cur:
        execute_values(cur, insert_query, data)


def _chunk_list(values, chunk_size=10000):
    for i in range(0, len(values), chunk_size):
        yield values[i:i + chunk_size]
